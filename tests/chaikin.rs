//! Chaikin creasing tests, validated against OpenSubdiv 3.7.0.
//!
//! The reference values were produced by running the same mesh through
//! OpenSubdiv's `Far::TopologyRefinerFactory`, `Far::PrimvarRefiner::Interpolate`
//! and `Far::PrimvarRefiner::Limit` (uniform refinement to level 2 with
//! `fullTopologyInLastLevel`).

use opensubdiv_rs::far::{
    PrimvarRefiner, TopologyDescriptor, TopologyRefiner, TopologyRefinerFactory, UniformOptions,
};
use opensubdiv_rs::sdc;

type P3 = [f32; 3];

/// A 3x2 quad strip on a 4x3 vertex grid with a semi-sharp crease chain
/// (2.0 / 1.0 / 2.0) running along the middle row, from boundary vertex 4 to
/// boundary vertex 7:
///
/// ```text
///   8 --- 9 --- 10 --- 11
///   |     |     |      |
///   4 === 5 === 6 ==== 7
///   |     |     |      |
///   0 --- 1 --- 2 ---- 3
/// ```
///
/// At the boundary ends the crease meets two infinitely sharp boundary
/// edges, which must not take part in the Chaikin average.
const Z: [f32; 12] = [0.0, 0.3, -0.2, 0.1, 0.4, 0.8, 0.6, 0.2, -0.1, 0.2, 0.5, 0.0];
const CREASE_PAIRS: [[u32; 2]; 3] = [[4, 5], [5, 6], [6, 7]];
const CREASE_WEIGHTS: [f32; 3] = [2.0, 1.0, 2.0];

fn strip_positions() -> Vec<P3> {
    (0..12)
        .map(|v| [(v % 4) as f32, (v / 4) as f32, Z[v]])
        .collect()
}

fn strip_refiner(levels: usize) -> TopologyRefiner {
    let verts_per_face = [4usize; 6];
    let mut face_verts: Vec<u32> = Vec::new();
    for j in 0..2u32 {
        for i in 0..3u32 {
            let v = j * 4 + i;
            face_verts.extend_from_slice(&[v, v + 1, v + 5, v + 4]);
        }
    }
    let descriptor = TopologyDescriptor::new(12, &verts_per_face, &face_verts)
        .with_creases(&CREASE_PAIRS, &CREASE_WEIGHTS);
    let options = sdc::Options::default()
        .with_vtx_boundary_interpolation(sdc::VtxBoundaryInterpolation::EdgeOnly)
        .with_creasing_method(sdc::CreasingMethod::Chaikin);
    let mut refiner =
        TopologyRefinerFactory::create(descriptor, sdc::SchemeType::Catmark, options).unwrap();
    refiner.refine_uniform(UniformOptions::new(levels));
    refiner
}

fn assert_close(actual: P3, expected: P3, what: &str) {
    for (a, e) in actual.iter().zip(&expected) {
        assert!(
            (a - e).abs() < 1e-5,
            "{what}: expected {expected:?}, got {actual:?}"
        );
    }
}

#[test]
fn chaikin_child_sharpness_ignores_infinite_boundary_neighbors() {
    let refiner = strip_refiner(1);
    let base = refiner.level(0);
    let level1 = refiner.level(1);
    let num_base_faces = base.num_faces() as u32;
    let num_base_edges = base.num_edges() as u32;
    // Level-1 vertices: face children, then edge children, then vertex children.
    let vertex_child = |v: u32| num_base_faces + num_base_edges + v;
    let edge_child = |a: u32, b: u32| num_base_faces + base.find_edge(a, b).unwrap();
    let child_sharpness =
        |a: u32, b: u32| level1.edge_sharpness(level1.find_edge(a, b).unwrap() as usize);

    // Values from OpenSubdiv. The 2.0 edges meet only infinitely sharp
    // boundary edges at the boundary, so they decrement uniformly there
    // (2.0 - 1 = 1.0); at the interior they blend with the 1.0 edge
    // (0.75 * 2 + 0.25 * 1 - 1 = 0.75).
    let expected = [
        (4, 5, 4, 1.0),
        (4, 5, 5, 0.75),
        (5, 6, 5, 0.25),
        (5, 6, 6, 0.25),
        (6, 7, 6, 0.75),
        (6, 7, 7, 1.0),
    ];
    for (a, b, end, sharpness) in expected {
        let s = child_sharpness(edge_child(a, b), vertex_child(end));
        assert!(
            (s - sharpness).abs() < 1e-6,
            "child of edge ({a}, {b}) at vertex {end}: expected {sharpness}, got {s}"
        );
    }
}

#[test]
fn chaikin_crease_ending_on_boundary_matches_opensubdiv() {
    let refiner = strip_refiner(2);
    let primvar = PrimvarRefiner::new(&refiner);
    let levels = primvar.interpolate_all(&strip_positions());
    let refined = &levels[1];
    let mut limit = vec![[0.0f32; 3]; refined.len()];
    primvar.limit(refined, &mut limit);

    // Vertex numbering of a level may differ from OpenSubdiv's (edge order
    // does), and so may the order of child faces and of their corners, so
    // match each face to the reference face with the same refined corner
    // positions (up to rotation) and compare limit positions through that
    // correspondence.
    let level2 = refiner.level(2);
    assert_eq!(level2.num_faces(), FACE_VERTS.len());
    assert_eq!(level2.num_vertices(), REFINED.len());
    let close = |a: P3, b: P3| a.iter().zip(&b).all(|(x, y)| (x - y).abs() < 1e-5);
    let mut matched = [false; FACE_VERTS.len()];
    for f in 0..level2.num_faces() {
        let ours = level2.face_vertices(f);
        let (g, rotation) = (0..FACE_VERTS.len())
            .filter(|&g| !matched[g])
            .flat_map(|g| (0..4).map(move |r| (g, r)))
            .find(|&(g, r)| {
                (0..4).all(|i| {
                    close(
                        refined[ours[i] as usize],
                        REFINED[FACE_VERTS[g][(i + r) % 4] as usize],
                    )
                })
            })
            .unwrap_or_else(|| {
                let corners: Vec<P3> = ours.iter().map(|&v| refined[v as usize]).collect();
                panic!("face {f} with refined corners {corners:?} matches no reference face")
            });
        matched[g] = true;
        for i in 0..4 {
            let what = format!("limit at face {f}, corner {i}");
            let theirs = FACE_VERTS[g][(i + rotation) % 4] as usize;
            assert_close(limit[ours[i] as usize], LIMIT[theirs], &what);
        }
    }
}

